#!/usr/bin/env python3
"""Reproducible Olist order-fulfilment analysis. Python standard library only.

The original Olist CSV files are NOT bundled. Supply unmodified CSVs from Kaggle.
No synthetic commercial transaction is generated by this script.
"""
from __future__ import annotations
import argparse
import csv
import json
from collections import Counter, defaultdict
from datetime import datetime
from decimal import Decimal, InvalidOperation
from pathlib import Path
from statistics import mean

FILES = {
    'orders':'olist_orders_dataset.csv',
    'items':'olist_order_items_dataset.csv',
    'payments':'olist_order_payments_dataset.csv',
    'reviews':'olist_order_reviews_dataset.csv',
    'products':'olist_products_dataset.csv',
    'sellers':'olist_sellers_dataset.csv',
    'customers':'olist_customers_dataset.csv',
    'translations':'product_category_name_translation.csv',
}
REQUIRED = {
    'orders': {'order_id','customer_id','order_status','order_purchase_timestamp','order_delivered_customer_date','order_estimated_delivery_date'},
    'items': {'order_id','order_item_id','product_id','seller_id','price','freight_value'},
    'payments': {'order_id','payment_value','payment_type'},
    'reviews': {'order_id','review_score'},
    'products': {'product_id','product_category_name'},
    'sellers': {'seller_id','seller_city','seller_state'},
    'customers': {'customer_id','customer_state'},
    'translations': {'product_category_name','product_category_name_english'},
}

def rows(path, required):
    with path.open('r',encoding='utf-8-sig',newline='') as h:
        rd=csv.DictReader(h)
        if rd.fieldnames is None: raise ValueError(f'{path}: missing headers')
        missing=required-set(rd.fieldnames)
        if missing: raise ValueError(f'{path}: missing columns {sorted(missing)}')
        yield from rd

def money(value,context):
    try:
        n=Decimal((value or '').strip())
    except (InvalidOperation,AttributeError): raise ValueError(f'Invalid BRL amount at {context}: {value!r}')
    if not n.is_finite() or n<0: raise ValueError(f'Negative/non-finite BRL amount at {context}')
    return n

def stamp(value):
    if not value: return None
    return datetime.fromisoformat(value.strip().replace('Z','+00:00'))

def write_csv(path,fields,data):
    path.parent.mkdir(parents=True,exist_ok=True)
    with path.open('w',encoding='utf-8',newline='') as h:
        wr=csv.DictWriter(h,fieldnames=fields)
        wr.writeheader()
        for row in data: wr.writerow(row)

def build(raw,output):
    missing=[f for f in FILES.values() if not (raw/f).is_file()]
    if missing: raise FileNotFoundError('Missing original Olist CSVs in '+str(raw)+': '+', '.join(missing))
    output.mkdir(parents=True,exist_ok=True)
    products={}
    for r in rows(raw/FILES['products'],REQUIRED['products']):
        if r['product_id'] in products: raise ValueError('Duplicate product_id')
        products[r['product_id']]=r['product_category_name'] or 'unclassified'
    translations={r['product_category_name']:r['product_category_name_english'] for r in rows(raw/FILES['translations'],REQUIRED['translations'])}
    sellers={}
    for r in rows(raw/FILES['sellers'],REQUIRED['sellers']):
        if r['seller_id'] in sellers: raise ValueError('Duplicate seller_id')
        sellers[r['seller_id']]=r
    customers={}
    for r in rows(raw/FILES['customers'],REQUIRED['customers']):
        if r['customer_id'] in customers: raise ValueError('Duplicate customer_id')
        customers[r['customer_id']]=r
    orders={}
    for r in rows(raw/FILES['orders'],REQUIRED['orders']):
        if r['order_id'] in orders: raise ValueError('Duplicate order_id')
        if not r['order_purchase_timestamp']: raise ValueError('Missing purchase timestamp')
        orders[r['order_id']]=r
    item_total=defaultdict(lambda:[Decimal('0'),Decimal('0'),0])
    seller_stats=defaultdict(lambda:{'orders':set(),'item_lines':0,'item_value':Decimal('0'),'freight':Decimal('0')})
    cat_stats=defaultdict(lambda:{'orders':set(),'item_lines':0,'item_value':Decimal('0'),'freight':Decimal('0')})
    missing_item_order=0; missing_products=0;missing_sellers=0;item_rows=0
    for r in rows(raw/FILES['items'],REQUIRED['items']):
        item_rows+=1;id=r['order_id'];pr=money(r['price'],f'items:{item_rows}');fr=money(r['freight_value'],f'freight:{item_rows}')
        if id not in orders: missing_item_order+=1;continue
        totals=item_total[id];totals[0]+=pr;totals[1]+=fr;totals[2]+=1
        seller=r['seller_id']; cat_orig=products.get(r['product_id'])
        if not cat_orig: missing_products+=1;cat_orig='unclassified'
        if seller not in sellers: missing_sellers+=1
        cat=translations.get(cat_orig,cat_orig)
        ss=seller_stats[seller];ss['orders'].add(id);ss['item_lines']+=1;ss['item_value']+=pr;ss['freight']+=fr
        cs=cat_stats[cat];cs['orders'].add(id);cs['item_lines']+=1;cs['item_value']+=pr;cs['freight']+=fr
    payments=defaultdict(lambda:Decimal('0'));payment_rows=0;missing_payment_order=0
    for r in rows(raw/FILES['payments'],REQUIRED['payments']):
        payment_rows+=1
        if r['order_id'] not in orders:missing_payment_order+=1;continue
        payments[r['order_id']]+=money(r['payment_value'],f'payments:{payment_rows}')
    reviews=defaultdict(list);review_rows=0;missing_review_order=0
    for r in rows(raw/FILES['reviews'],REQUIRED['reviews']):
        review_rows+=1
        if r['order_id'] not in orders:missing_review_order+=1;continue
        try: score=int(r['review_score'])
        except (ValueError,TypeError):continue
        if 1<=score<=5:reviews[r['order_id']].append(score)
    bad_customer_keys=sum(1 for r in orders.values() if r['customer_id'] not in customers)
    daily=defaultdict(lambda: {'orders':0,'delivered':0,'on_time':0,'late':0,'eligible':0,'delay_days_sum':0,'item_value':Decimal('0'),'freight':Decimal('0')})
    output_rows=[];statuses=Counter();delivered=0;eligible=0;ontime=0;late=0;cancelled=0;missing_delivery_date=0;missing_estimate_date=0;lead_days=[];late_days=[]
    for id,r in orders.items():
        purchase=stamp(r['order_purchase_timestamp']);actual=stamp(r['order_delivered_customer_date']);estimate=stamp(r['order_estimated_delivery_date'])
        status=r['order_status'];statuses[status]+=1;month=purchase.strftime('%Y-%m'); d=daily[month];d['orders']+=1
        subt,freight,count=item_total[id];d['item_value']+=subt;d['freight']+=freight
        if status=='cancelled':cancelled+=1
        if status=='delivered':
            delivered+=1;d['delivered']+=1
            if actual is None: missing_delivery_date+=1
            if estimate is None:missing_estimate_date+=1
        qualify=status=='delivered' and actual is not None and estimate is not None
        delta=(actual.date()-estimate.date()).days if qualify else None
        if qualify:
            eligible+=1;d['eligible']+=1
            if delta<=0: ontime+=1;d['on_time']+=1
            else:late+=1;d['late']+=1;d['delay_days_sum']+=delta;late_days.append(delta)
            lead_days.append((actual-purchase).total_seconds()/86400)
        scores=reviews.get(id,[])
        state=customers.get(r['customer_id'],{}).get('customer_state','')
        output_rows.append({'order_id':id,'purchase_month':month,'order_status':status,'customer_state':state,'purchase_date':purchase.date().isoformat(),
            'actual_delivery_date':actual.date().isoformat() if actual else '',
            'estimated_delivery_date':estimate.date().isoformat() if estimate else '',
            'delivery_days_from_estimate':delta if delta is not None else '',
            'on_time_eligible':int(qualify),'on_time_flag':int(qualify and delta<=0),
            'item_lines':count,'item_value_brl':str(subt),'freight_value_brl':str(freight),
            'payment_value_brl':str(payments.get(id,Decimal('0'))),'review_score_avg':round(mean(scores),2) if scores else '',
            'review_count':len(scores)})
    month_out=[]
    for month,vals in sorted(daily.items()):
        month_out.append({'month':month,'orders':vals['orders'],'delivered':vals['delivered'],'on_time_eligible':vals['eligible'],
            'on_time_deliveries':vals['on_time'],'late_deliveries':vals['late'],
            'on_time_delivery_pct':round(vals['on_time']/vals['eligible']*100,2) if vals['eligible'] else '',
            'avg_late_days':round(vals['delay_days_sum']/vals['late'],2) if vals['late'] else '',
            'item_value_brl':str(vals['item_value']),'freight_value_brl':str(vals['freight'])})
    seller_out=[]
    for sid,x in seller_stats.items():
        rr=sellers.get(sid,{})
        seller_out.append({'seller_id':sid,'seller_state':rr.get('seller_state',''),'seller_city':rr.get('seller_city',''),
            'order_count_attributed':len(x['orders']),'item_lines':x['item_lines'],'item_value_brl':str(x['item_value']),'freight_brl':str(x['freight'])})
    seller_out.sort(key=lambda r:Decimal(r['item_value_brl']),reverse=True)
    cat_out=[]
    for category,x in cat_stats.items():cat_out.append({'category':category,'order_count_attributed':len(x['orders']),'item_lines':x['item_lines'],'item_value_brl':str(x['item_value']),'freight_brl':str(x['freight'])})
    cat_out.sort(key=lambda r:Decimal(r['item_value_brl']),reverse=True)
    state_counts=Counter(r['seller_state'] for r in sellers.values())
    state_out=[{'state':state,'sellers':n} for state,n in state_counts.most_common()]
    write_csv(output/'orders_enriched.csv',list(output_rows[0]),output_rows)
    write_csv(output/'monthly_metrics.csv',list(month_out[0]),month_out)
    write_csv(output/'seller_summary.csv',list(seller_out[0]),seller_out)
    write_csv(output/'category_summary.csv',list(cat_out[0]),cat_out)
    write_csv(output/'seller_state_counts.csv',['state','sellers'],state_out)
    kpis={
        'source':'Olist Brazilian E-Commerce Public Dataset by Olist - Kaggle',
        'data_status':'FULL_OLIST_DATA_LOADED',
        'source_url':'https://www.kaggle.com/datasets/olistbr/brazilian-ecommerce',
        'currency':'BRL','orders':len(orders),'delivered_orders':delivered,'eligible_delivered_orders':eligible,
        'on_time_deliveries':ontime,'late_deliveries':late,'on_time_delivery_rate_pct':round(100*ontime/eligible,2) if eligible else None,
        'avg_delivery_lead_days':round(mean(lead_days),2) if lead_days else None,
        'avg_late_days':round(mean(late_days),2) if late_days else None,
        'cancelled_orders':cancelled,'cancellation_rate_pct':round(100*cancelled/len(orders),2) if orders else None,
        'item_value_brl':str(sum((r[0] for r in item_total.values()),Decimal('0'))),
        'freight_value_brl':str(sum((r[1] for r in item_total.values()),Decimal('0'))),
        'payment_value_brl':str(sum(payments.values(),Decimal('0'))),
        'seller_count':len(sellers),'category_count':len(cat_stats),
        'source_rows':{'orders':len(orders),'items':item_rows,'payments':payment_rows,'reviews':review_rows,'sellers':len(sellers),'products':len(products),'customers':len(customers)},
        'qa':{'unique_order_ids':len(orders)==len(output_rows),'missing_item_order_refs':missing_item_order,
              'missing_payment_order_refs':missing_payment_order,'missing_review_order_refs':missing_review_order,
              'missing_product_refs':missing_products,'missing_seller_refs':missing_sellers,
              'missing_customer_refs':bad_customer_keys,'delivered_missing_actual_date':missing_delivery_date,
              'delivered_missing_estimate_date':missing_estimate_date,
              'monthly_reconciles':sum(r['orders'] for r in month_out)==len(orders),
              'item_aggregation_reconciles':sum((Decimal(r['item_value_brl']) for r in seller_out),Decimal('0'))==sum((v[0] for v in item_total.values()),Decimal('0')),
              'category_aggregation_reconciles':sum((Decimal(r['item_value_brl']) for r in cat_out),Decimal('0'))==sum((v[0] for v in item_total.values()),Decimal('0'))},
        'definitions':{'on_time':'status=delivered and both actual and estimated delivery dates present; actual calendar date <= estimated calendar date',
                       'amount':'sum order-item price and freight per order; payment values aggregated per order; never direct items x payments join',
                       'seller':'marketplace seller, not upstream supplier',
                       'review':'mean of valid review scores within order, if multiple reviews; do not count same order multiple times'}
    }
    (output/'kpi_summary.json').write_text(json.dumps(kpis,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
    return kpis

if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--raw',type=Path,default=Path('data/raw'))
    ap.add_argument('--output',type=Path,default=Path('data/processed'))
    a=ap.parse_args();res=build(a.raw,a.output)
    print(json.dumps({'orders':res['orders'],'on_time_delivery_rate_pct':res['on_time_delivery_rate_pct'],'qa':res['qa']},indent=2))
